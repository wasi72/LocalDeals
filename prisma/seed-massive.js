async function main() {
  console.log(`Starting massive seeding of ${MASSIVE_DEALS.length} worldwide deals...`);

  // 1. Fetch categories
  const categories = await prisma.category.findMany();
  const catMap = {};
  for (const c of categories) {
    catMap[c.slug] = c.id;
  }
  const defaultCatId = categories[0].id;

  const now = new Date();
  const ends30Days = new Date(now.getTime() + 30 * 24 * 60 * 60 * 1000);

  let createdCount = 0;
  let updatedCount = 0;

  for (const d of MASSIVE_DEALS) {
    const merchantEmail = `partner.${d.slug.replace(/[^a-z0-9]/g, '')}@localdeals-hub.com`;

    const merchant = await prisma.user.upsert({
      where: { email: merchantEmail },
      update: { city: d.city, postcode: d.postcode },
      create: {
        email: merchantEmail,
        name: `Local Partner (${d.bizName})`,
        role: 'MERCHANT',
        city: d.city,
        postcode: d.postcode,
      },
    });

    const biz = await prisma.business.upsert({
      where: { slug: d.slug },
      update: {
        name: d.bizName,
        city: d.city,
        country: d.country,
        postcode: d.postcode,
        latitude: d.lat,
        longitude: d.lng,
        isVerified: true,
        status: 'ACTIVE',
      },
      create: {
        ownerId: merchant.id,
        name: d.bizName,
        slug: d.slug,
        description: d.desc,
        address: `${d.city} Central District`,
        city: d.city,
        postcode: d.postcode,
        country: d.country,
        latitude: d.lat,
        longitude: d.lng,
        isVerified: true,
        status: 'ACTIVE',
      },
    });

    const existingOffer = await prisma.offer.findFirst({
      where: {
        businessId: biz.id,
        title: d.title,
      },
    });

    if (!existingOffer) {
      await prisma.offer.create({
        data: {
          businessId: biz.id,
          categoryId: catMap[d.catSlug] || defaultCatId,
          title: d.title,
          description: d.desc,
          terms: d.terms,
          discountType: 'FIXED_AMOUNT',
          originalPriceCents: d.origCents,
          discountPriceCents: d.discCents,
          discountPercentage: d.pct,
          currency: d.currency,
          isFeatured: d.isFeatured || false,
          status: 'APPROVED',
          startsAt: now,
          endsAt: ends30Days,
          redemptionLimit: 100,
          imageUrl: d.img,
        },
      });
      createdCount++;
    } else {
      await prisma.offer.update({
        where: { id: existingOffer.id },
        data: {
          originalPriceCents: d.origCents,
          discountPriceCents: d.discCents,
          discountPercentage: d.pct,
          currency: d.currency,
          isFeatured: d.isFeatured || false,
          status: 'APPROVED',
          endsAt: ends30Days,
        },
      });
      updatedCount++;
    }
  }

  const totalOffers = await prisma.offer.count({ where: { status: 'APPROVED' } });
  console.log(`Massive seeding complete! Created: ${createdCount}, Updated: ${updatedCount}, Total Active Offers in DB: ${totalOffers}`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
